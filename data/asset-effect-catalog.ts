export function filterEffects(category = 'all', query = '') {
  const terms = query.trim().toLocaleLowerCase().split(/\s+/).filter(Boolean);
  return effectCatalog.filter(
    (effect) =>
      (category === 'all' ||
        effect.category === category ||
        effectCategories.find((item) => item.id === effect.category)?.usage ===
          category) &&
      terms.every((term) =>
        `${effect.ja} ${effect.promptJa} ${effect.en} ${effectCategories.find((item) => item.id === effect.category)?.ja} ${effectCategories.find((item) => item.id === effect.category)?.en}`
          .toLocaleLowerCase()
          .includes(term),
      ),
  );
}
